/**
 * Merge a bitmap into horizontal runs, which is far fewer rectangles than
 * one per pixel.
 * @param {Bitmap} rows
 * @returns {Array<[number, number, number, number]>} [x, y, w, h] runs
 */
export function bitmapRects(rows) {
  /** @type {Array<[number, number, number, number]>} */
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === "#") end++;
      rects.push([x, y, end - x, 1]);
      x = end;
    }
  });
  return rects;
}

/** @param {string} name @param {number} [frame] */
export function spriteFrame(name, frame = 0) {
  const frames = SPRITES[name];
  return frames[Math.abs(Math.trunc(frame)) % frames.length];
}

/** @param {string} name @returns {{ w: number, h: number }} */
export function spriteSize(name) {
  const rows = SPRITES[name][0];
  return { w: rows[0].length, h: rows.length };
}

/** @param {string} ch The glyph, or "?" if the font lacks it. */
export function glyphFor(ch) {
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT["?"];
}

/**
 * Width in output units of a string at a scale. One column of spacing sits
 * between glyphs.
 * @param {string} text @param {number} [scale]
 */
export function textWidth(text, scale = 1) {
  const n = [...text].length;
  return n === 0 ? 0 : (n * (GLYPH_W + 1) - 1) * scale;
}
