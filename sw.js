// Minimal service worker: the homepage shell works offline, and pages are
// served network-first so new deploys appear immediately when online.
// Experiments are cached opportunistically once visited; none opt in yet.

const VERSION = "dev"; // Replaced with a content hash at deploy time.
const CACHE = `vibes-${VERSION}`;
const SHELL = [
  "./",
  "manifest.webmanifest",
  "favicon.svg",
  "icons/apple-touch-icon.png",
  "icons/icon-192.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("vibes-") && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== location.origin) return;

  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok && response.type === "basic") {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(async () => {
        const cached = await caches.match(request, { ignoreSearch: true });
        return cached ?? Response.error();
      }),
  );
});
